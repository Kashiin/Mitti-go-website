/* Blog, article and 404 pages: theme switch, mobile menu, remembering the chosen language.
   All page content is static HTML generated by tools/build.mjs.
   Handlers are delegated on document, so they keep working when the 404 page swaps its language version. */
(function(){
var root=document.documentElement;
function q(s){return document.querySelector(s)}
function isDark(){var t=root.getAttribute("data-theme");return t?t==="dark":matchMedia("(prefers-color-scheme: dark)").matches}
function syncThemeIcon(){var i=q("#themeIc");if(i)i.textContent=isDark()?"light_mode":"dark_mode"}
function setMnav(open){var m=q("#mnav"),b=q("#burger"),i=q("#burgerIc");if(!m||!b)return;m.classList.toggle("open",open);b.setAttribute("aria-expanded",open);if(i)i.textContent=open?"close":"menu"}
document.addEventListener("click",function(e){
  var t=e.target;
  if(t.closest("#themeBtn")){var th=isDark()?"light":"dark";root.setAttribute("data-theme",th);syncThemeIcon();try{localStorage.setItem("mg-theme",th)}catch(x){}return}
  if(t.closest("#burger")){var m=q("#mnav");setMnav(!(m&&m.classList.contains("open")));return}
  if(t.closest("#mnav a"))setMnav(false);
  var a=t.closest("a[hreflang]");
  if(a){try{localStorage.setItem("mg-lang",a.getAttribute("hreflang"))}catch(x){}}
});
try{var st=localStorage.getItem("mg-theme");if(st==="light"||st==="dark")root.setAttribute("data-theme",st)}catch(e){}
syncThemeIcon();
try{matchMedia("(prefers-color-scheme: dark)").addEventListener("change",syncThemeIcon)}catch(e){}
window.MGSite={syncThemeIcon:syncThemeIcon};
})();
